def terraform_export(d: LZDesign) -> str:
    n_env = [e for e in d.environments]
    workloads = [f"workload-{i + 1}" for i in range(d.num_workloads)]
    per_env = d.account_strategy == "Account per workload per environment"
    per_wl = d.account_strategy in ("Account per workload", "Account per workload per environment")

    out = []
    out.append(f'''# ---------------------------------------------------------------
# AWS Landing Zone — generated by AWS Landing Zone Studio
# Strategy: {d.account_strategy} | Network: {d.network_pattern}
# Review carefully before applying. Account emails MUST be unique.
# ---------------------------------------------------------------

terraform {{
  required_version = ">= 1.5"
  required_providers {{
    aws = {{ source = "hashicorp/aws", version = ">= 5.40" }}
  }}
}}

provider "aws" {{
  region = "{d.regions[0] if d.regions else 'us-east-1'}"
  # Run from the management account (or a delegated admin for Organizations)
}}

variable "account_email_domain" {{
  description = "Domain used for root emails, e.g. aws+%s@example.com"
  type        = string
}}

locals {{
  environments = {json.dumps(n_env)}
  workloads    = {json.dumps(workloads)}
  approved_regions = {json.dumps(d.regions)}
}}

# ----------------------------- Organization -----------------------------

resource "aws_organizations_organization" "this" {{
  feature_set = "ALL"
  enabled_policy_types = ["SERVICE_CONTROL_POLICY", "TAG_POLICY"]
  aws_service_access_principals = [
    "cloudtrail.amazonaws.com",
    "config.amazonaws.com",
    "guardduty.amazonaws.com",
    "securityhub.amazonaws.com",
    "sso.amazonaws.com",
    "backup.amazonaws.com",
  ]
}}

# ----------------------------- OU structure -----------------------------

resource "aws_organizations_organizational_unit" "security" {{
  name      = "Security"
  parent_id = aws_organizations_organization.this.roots[0].id
}}

resource "aws_organizations_organizational_unit" "infrastructure" {{
  name      = "Infrastructure"
  parent_id = aws_organizations_organization.this.roots[0].id
}}

resource "aws_organizations_organizational_unit" "workloads" {{
  name      = "Workloads"
  parent_id = aws_organizations_organization.this.roots[0].id
}}
''')

    if per_env:
        out.append('''
resource "aws_organizations_organizational_unit" "workloads_prod" {
  name      = "Prod"
  parent_id = aws_organizations_organizational_unit.workloads.id
}

resource "aws_organizations_organizational_unit" "workloads_nonprod" {
  name      = "NonProd"
  parent_id = aws_organizations_organizational_unit.workloads.id
}
''')

    out.append('''
resource "aws_organizations_organizational_unit" "sandbox" {
  name      = "Sandbox"
  parent_id = aws_organizations_organization.this.roots[0].id
}

resource "aws_organizations_organizational_unit" "suspended" {
  name      = "Suspended"
  parent_id = aws_organizations_organization.this.roots[0].id
}

# ----------------------------- Core accounts -----------------------------

resource "aws_organizations_account" "log_archive" {
  name      = "log-archive"
  email     = format(var.account_email_domain, "log-archive")
  parent_id = aws_organizations_organizational_unit.security.id
  role_name = "OrganizationAccountAccessRole"
  close_on_deletion = false
  lifecycle { prevent_destroy = true }
}

resource "aws_organizations_account" "security_tooling" {
  name      = "security-tooling"
  email     = format(var.account_email_domain, "security-tooling")
  parent_id = aws_organizations_organizational_unit.security.id
  role_name = "OrganizationAccountAccessRole"
  close_on_deletion = false
  lifecycle { prevent_destroy = true }
}
''')

    if d.network_pattern != "Flat VPC peering":
        out.append('''
resource "aws_organizations_account" "network" {
  name      = "network"
  email     = format(var.account_email_domain, "network")
  parent_id = aws_organizations_organizational_unit.infrastructure.id
  role_name = "OrganizationAccountAccessRole"
  close_on_deletion = false
  lifecycle { prevent_destroy = true }
}
''')

    out.append('''
resource "aws_organizations_account" "shared_services" {
  name      = "shared-services"
  email     = format(var.account_email_domain, "shared-services")
  parent_id = aws_organizations_organizational_unit.infrastructure.id
  role_name = "OrganizationAccountAccessRole"
  close_on_deletion = false
  lifecycle { prevent_destroy = true }
}

# ---------------------------- Workload accounts ----------------------------
''')

    if per_env:
        out.append('''
locals {
  workload_accounts = {
    for pair in setproduct(local.workloads, local.environments) :
    "${pair[0]}-${pair[1]}" => {
      workload = pair[0]
      env      = pair[1]
      prod     = pair[1] == "prod"
    }
  }
}

resource "aws_organizations_account" "workload" {
  for_each  = local.workload_accounts
  name      = each.key
  email     = format(var.account_email_domain, each.key)
  parent_id = each.value.prod ? aws_organizations_organizational_unit.workloads_prod.id : aws_organizations_organizational_unit.workloads_nonprod.id
  role_name = "OrganizationAccountAccessRole"
  close_on_deletion = false
}
''')
    elif per_wl:
        out.append('''
resource "aws_organizations_account" "workload" {
  for_each  = toset(local.workloads)
  name      = each.key
  email     = format(var.account_email_domain, each.key)
  parent_id = aws_organizations_organizational_unit.workloads.id
  role_name = "OrganizationAccountAccessRole"
  close_on_deletion = false
}
''')
    elif d.account_strategy == "Account per environment":
        out.append('''
resource "aws_organizations_account" "workload" {
  for_each  = toset(local.environments)
  name      = "workloads-${each.key}"
  email     = format(var.account_email_domain, "workloads-${each.key}")
  parent_id = aws_organizations_organizational_unit.workloads.id
  role_name = "OrganizationAccountAccessRole"
  close_on_deletion = false
}
''')

    # SCPs
    out.append("\n# ------------------------- Service Control Policies -------------------------\n")
    scp_targets = {
        "deny_leave_org": "aws_organizations_organization.this.roots[0].id",
        "deny_root_user": "aws_organizations_organizational_unit.workloads.id",
        "region_restriction": "aws_organizations_organization.this.roots[0].id",
        "protect_security_services": "aws_organizations_organization.this.roots[0].id",
        "deny_imdsv1": "aws_organizations_organizational_unit.workloads.id",
    }
    for name, doc in _SCP_DOCS.items():
        out.append(f'''
resource "aws_organizations_policy" "{name}" {{
  name    = "{name.replace('_', '-')}"
  type    = "SERVICE_CONTROL_POLICY"
  content = jsonencode({_hcl_jsonencode(doc, d.regions)})
}}

resource "aws_organizations_policy_attachment" "{name}" {{
  policy_id = aws_organizations_policy.{name}.id
  target_id = {scp_targets[name]}
}}
''')

    out.append('''
# Suspended OU: deny everything
resource "aws_organizations_policy" "suspended_deny_all" {
  name = "suspended-deny-all"
  type = "SERVICE_CONTROL_POLICY"
  content = jsonencode({
    Version = "2012-10-17"
    Statement = [{ Sid = "DenyAll", Effect = "Deny", Action = "*", Resource = "*" }]
  })
}

resource "aws_organizations_policy_attachment" "suspended_deny_all" {
  policy_id = aws_organizations_policy.suspended_deny_all.id
  target_id = aws_organizations_organizational_unit.suspended.id
}
''')
    return "".join(out)


