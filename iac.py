def control_tower_checklist(d: LZDesign) -> str:
    per_env = d.account_strategy == "Account per workload per environment"
    home = d.regions[0] if d.regions else "us-east-1"
    md = [f"""# Control Tower Setup — {d.org_size} profile

## 1. Prerequisites
- [ ] Management account with billing + root access secured (MFA, no access keys)
- [ ] Two fresh email addresses for **Log Archive** and **Audit** accounts
- [ ] Home region: **{home}** (governed regions: {', '.join(d.regions)})

## 2. Launch Control Tower
- [ ] Console -> Control Tower -> Set up landing zone
- [ ] Foundational OU: `Security` (Log Archive + Audit created automatically)
- [ ] Additional OU: `Workloads`{' with `Prod` / `NonProd` children' if per_env else ''}
- [ ] Enable AWS CloudTrail org trail (mandatory control)
- [ ] KMS encryption for Control Tower resources: **enabled**

## 3. Post-launch configuration
- [ ] Create OUs: `Infrastructure`, `Sandbox`, `Suspended` (register each with CT)
- [ ] Enable IAM Identity Center; connect {"external IdP (" + d.identity_model + ")" if d.identity_model.startswith("External") else "Identity Center directory"}
- [ ] Delegate GuardDuty + Security Hub + Config admin to the **Audit** account
- [ ] Apply elective/proactive controls per compliance: {', '.join(d.compliance) or 'baseline only'}

## 4. Account Factory
Provision accounts with these inputs:

| Account | OU | Purpose |
|---|---|---|
| network | Infrastructure | {d.network_pattern} hub |
| shared-services | Infrastructure | CI/CD, AMIs, registries |"""]
    if per_env:
        md.append("".join(
            f"\n| workload-{i + 1}-{e} | Workloads/{'Prod' if e == 'prod' else 'NonProd'} | Workload account |"
            for i in range(min(d.num_workloads, 20)) for e in d.environments))
    else:
        md.append("".join(
            f"\n| workload-{i + 1} | Workloads | Workload account |"
            for i in range(min(d.num_workloads, 20))))

    md.append(f"""

## 5. Network ({d.network_pattern})
- [ ] Provision Transit Gateway / core network in the **network** account
- [ ] Share via AWS RAM with the Workloads OU
- [ ] {"Centralize egress (NAT + inspection) in the network account" if "egress" in d.network_pattern.lower() else "Plan egress per the chosen pattern"}

## 6. Operations
- [ ] Account Factory Customization (AFT) or Customizations for Control Tower (CfCT) for baselines-as-code
- [ ] Budgets + budget actions on Sandbox OU
- [ ] {"AWS Backup org policies with cross-region copies" if d.backup_dr else "Define backup strategy per workload"}
""")
    return "".join(md)
