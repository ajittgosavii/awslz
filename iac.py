# Landing Zone Accelerator config
# ---------------------------------------------------------------------------

def lza_config(d: LZDesign) -> str:
    per_env = d.account_strategy == "Account per workload per environment"
    envs = d.environments
    home = d.regions[0] if d.regions else "us-east-1"

    lines = [f"""# organization-config.yaml — Landing Zone Accelerator
# Generated by AWS Landing Zone Studio. Review before deploying with LZA.
enable: true
organizationalUnits:
  - name: Security
  - name: Infrastructure
  - name: Workloads"""]
    if per_env:
        lines.append("""  - name: Workloads/Prod
  - name: Workloads/NonProd""")
    lines.append("""  - name: Sandbox
  - name: Suspended

serviceControlPolicies:
  - name: deny-leave-org
    description: Prevent accounts from leaving the organization
    policy: scp-deny-leave-org.json
    type: customerManaged
    deploymentTargets:
      organizationalUnits: [Root]
  - name: region-restriction
    description: Deny activity outside approved regions
    policy: scp-region-restriction.json
    type: customerManaged
    deploymentTargets:
      organizationalUnits: [Root]
  - name: protect-security-services
    description: Deny tampering with CloudTrail / Config / GuardDuty / Security Hub
    policy: scp-protect-security.json
    type: customerManaged
    deploymentTargets:
      organizationalUnits: [Root]
  - name: suspended-deny-all
    description: Quarantine policy
    policy: scp-deny-all.json
    type: customerManaged
    deploymentTargets:
      organizationalUnits: [Suspended]

taggingPolicies: []
backupPolicies: []""")

    lines.append(f"""

# accounts-config.yaml (fragment)
mandatoryAccounts:
  - name: Management
    description: Organization management account
    email: aws+management@example.com   # CHANGE ME
    organizationalUnit: Root
  - name: LogArchive
    description: Immutable centralized logs
    email: aws+log-archive@example.com  # CHANGE ME
    organizationalUnit: Security
  - name: Audit
    description: Security tooling / delegated admin
    email: aws+audit@example.com        # CHANGE ME
    organizationalUnit: Security

workloadAccounts:""")
    if per_env:
        for i in range(min(d.num_workloads, 50)):
            for e in envs:
                ou = "Workloads/Prod" if e == "prod" else "Workloads/NonProd"
                lines.append(f"""  - name: workload-{i + 1}-{e}
    email: aws+workload-{i + 1}-{e}@example.com  # CHANGE ME
    organizationalUnit: {ou}""")
    else:
        for i in range(min(d.num_workloads, 50)):
            lines.append(f"""  - name: workload-{i + 1}
    email: aws+workload-{i + 1}@example.com  # CHANGE ME
    organizationalUnit: Workloads""")

    lines.append(f"""

# global-config.yaml (fragment)
homeRegion: {home}
enabledRegions: {json.dumps(d.regions)}
managementAccountAccessRole: OrganizationAccountAccessRole
cloudwatchLogRetentionInDays: 365
centralizedLoggingBucket:
  lifecycleRules:
    - enabled: true
      expiration: 730
""")
    return "\n".join(lines)


